/**
 * 백업 링의 한계를 사용자에게 말할 때 쓰는 단 하나의 숫자.
 *
 * 왜 상수로 빼는가: 이 값은 화면 문구(`SAVE_CONFIRM_BACKUP_LIMIT`)와 회귀 테스트
 *   (`qa/test_restore_path.py`)가 같이 쓴다. 문구에 숫자를 박아 두면 둘이 조용히 어긋나고,
 *   어긋난 쪽이 화면이면 사용자에게 거짓 약속을 하게 된다.
 *
 * 왜 이 숫자인가: `disk` 백업과 `profile_*` 대피본이 `store.BACKUP_KEEP` 한 링을 공유한다.
 *   적용 1회가 링에 미는 개수는 사용 방식에 따라 다르다:
 *     · 게임을 안 띄우고 적용만 반복  → 0개/회 → 대피본이 밀리지 않는다
 *       (디스크가 어느 슬롯과도 다를 때만 백업한다. A↔B 왕복은 언제나 어느 한쪽과 같으므로
 *        링을 태우지 않는다.)
 *     · 게임이 설정을 다시 쓴 뒤 적용 → 1개/회 → 링 크기만큼에 소멸  ← 실사용은 이쪽이다
 *   낙관하지 않는 쪽을 고른다. 실측 최소보다 작은 값이라야 경고가 일찍 뜬다.
 *   그 검사가 두 갈래를 실제로 재고, 화면 숫자가 실사용 실측보다 크면 「안전을 과장했다」로
 *   떨어뜨린다. 숫자를 올리려면 그 검사를 다시 돌리고 이 주석을 같이 고칠 것.
 */
export const BACKUP_WARN_APPLIES = 5;

